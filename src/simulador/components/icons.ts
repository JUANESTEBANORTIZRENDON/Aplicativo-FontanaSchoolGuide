export type IconName = keyof typeof ICONS;

/** Marcador de ícono decorativo. */
export function icon(name: IconName | string, className = ''): string {
  return `<span class="sim-icon ${esc(className)}" data-sim-icon="${esc(name)}" aria-hidden="true"></span>`;
}

/** Reemplaza los marcadores pendientes dentro de `root` por el SVG correspondiente. */
export function hydrateIcons(root: ParentNode): void {
  for (const slot of root.querySelectorAll<HTMLElement>('[data-sim-icon]')) {
    if (slot.firstElementChild) continue;
    const node = ICONS[slot.dataset.simIcon as IconName];
    if (!node) continue;
    slot.append(createElement(node, { width: '1em', height: '1em', 'stroke-width': 2, focusable: 'false' }));
  }
}
